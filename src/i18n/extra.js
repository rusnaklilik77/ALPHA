// Рекурсивное слияние: вложенные объекты объединяются, остальное (строки,
// функции) — заменяется значением из extra.
export function deepMerge(target, source) {
  for (const key of Object.keys(source)) {
    const s = source[key];
    const isPlain = s && typeof s === "object" && !Array.isArray(s);
    if (isPlain && target[key] && typeof target[key] === "object") {
      deepMerge(target[key], s);
    } else {
      target[key] = s;
    }
  }
  return target;
}
